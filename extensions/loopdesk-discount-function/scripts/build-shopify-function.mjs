import { existsSync, rmSync, statSync } from "node:fs";
import { join } from "node:path";

const distDir = join(process.cwd(), "dist");
const wasmPath = join(distDir, "function.wasm");

if (existsSync(wasmPath)) rmSync(wasmPath);

throw new Error([
  "LoopDesk Discount Function is a JavaScript Shopify Function.",
  "Do not run a nested Shopify CLI function build from this extension build script.",
  "Shopify CLI's JavaScript Function pipeline builds this extension directly during `shopify app deploy`/`shopify app build` because `[extensions.build].command` is omitted in shopify.extension.toml.",
  "Run `shopify app build` or `shopify app deploy` from the app root to produce dist/function.wasm via Shopify's supported JS Function/Javy pipeline.",
  "No fallback function.wasm will be generated by this script.",
].join(" "));

if (!existsSync(wasmPath)) {
  throw new Error("Shopify JavaScript Function build completed without producing dist/function.wasm.");
}

const size = statSync(wasmPath).size;
if (size <= 8) {
  rmSync(wasmPath);
  throw new Error("Refusing synthetic/minimal function.wasm. Shopify's JavaScript Function/Javy pipeline must produce a real Shopify Function-compatible WASM artifact.");
}

console.log(`LoopDesk Discount Function WASM artifact generated: dist/function.wasm (${size} bytes)`);
